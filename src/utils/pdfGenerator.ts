/**
 * Triggers an immediate browser download of the report as an official PDF file.
 */
export function downloadMedicalReportPdf(report: MedicalReport, patientName = 'Vedant Pokale'): void {
  try {
    const blob = generatePdfBlob(report, patientName);
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    const cleanFileName = (report.fileName || `${report.title || 'medical_report'}.pdf`)
      .replace(/\s+/g, '_')
      .toLowerCase();
    link.download = cleanFileName.endsWith('.pdf') ? cleanFileName : `${cleanFileName}.pdf`;
    document.body.appendChild(link);
    link.click();
    setTimeout(() => {
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
    }, 1500);
  } catch (err) {
    console.error('Failed to download PDF report, opening printable view:', err);
    printMedicalReport(report, patientName);
  }
}

